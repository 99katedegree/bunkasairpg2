package main

// ============================================================================
// 世界設定 —— 『六輝（りっき）と、姿定めぬ竜』
//
// ここはコードではなく設定資料。エリア名・武器名・アイテム名・モンスター名は
// すべてこの物語から引かれている。名前を足すときも数値を触るときも、
// まずここを読むこと。
// ============================================================================
//
// ■ 六輝
//
// この世界は、六柱の精霊「六輝」に支えられていた。
//
//	無輝アルテナ  形なきものの精霊。鋼と石と、名を持たぬすべてに宿る
//	炎輝イグナ    火の精霊。灼き、鍛え、灰から生かす
//	水輝ミレイア  水の精霊。凍らせ、湛え、静かに沈める
//	森輝ヴェルデ  森の精霊。芽吹かせ、絡め、朽ちさせる
//	光輝ソレイユ  光の精霊。照らし、裁き、目を灼く
//	闇輝ノクス    闇の精霊。隠し、蝕み、眠らせる
//
// 六輝の加護が大地に満ち、剣は炎を纏い、弓は光を放ち、槌は大地の重さを得た。
// 武器が必ず「振るい方」と「属性」を一つずつ持つのは、鍛冶と加護の作法である。
//
//	斬（剣・双剣・斧・短剣・爪）
//	打（槌・拳・メイス・モーニングスター）
//	射（銃・弓・重銃・両手銃）
//
// ■ 姿定めぬ竜ヴァリアス
//
// ある日、空が裂けた。
// 裂け目から降りたのは、姿を定めぬ竜——ヴァリアスであった。
//
// ヴァリアスは形を持たない。炎を向ければ炎を纏い、光を向ければ光を鱗とする。
// 六輝は総力を挙げて竜を空の果てへ押し戻し、封印を施した。
// だがそれは六輝の力のほとんどを費やす業であり、六柱は加護を大地に散らして
// 眠りに就いた。散った加護は各地の武器に宿り、人の手に受け継がれていった。
//
// 幾星霜が過ぎ、封印は緩んでいる。
// 裂け目から漏れる竜の気配が獣を狂わせ、遺跡を蝕み、死者を歩かせている。
// 魔物とは、竜の気配に当てられて属性が歪んだ生き物のことをいう。
//
// ■ なぜ全属性の武器を揃えるのか
//
// ヴァリアスは戦いのさなかに纏う属性を変え続ける（battle/boss.go の
// ShiftWeakness が毎ターン弱点を移し替えている）。
// 一つの属性だけを携えて挑んでも、竜はその属性を鱗に変えて弾いてしまう。
//
//	姿定めぬものを討つには、六輝すべての加護を携えるほかない。
//
// これが最終地の武器 18 本が 3 つの振るい方 × 6 属性を網羅し、しかも
// 攻撃力の積を 2,000,000 で揃えてある理由である。18 本に優劣はない。
// 18 本すべてが要る。ゲームの都合ではなく、物語の結論がそうなっている。
//
// ■ 旅路
//
// 裂け目は空の果てにあり、そこへ至る道は六輝の加護が眠る土地を通る。
// 加護を新たに得る土地と、得るものがなく力だけを試される土地が交互に来る。
// 新しい土地を足すときは、まずどちらなのかを決めてから名前を付けること。
//
//	 1 陽だまりの草原    Lv1     加護: 無・炎・森      竜の気配が最も薄い、旅の始まりの地
//	 2 囁きの森          Lv5-9   加護: 水・光・闇      木々が声を持つ。四輝の加護が枝分かれする森
//	 3 鉄錆の廃坑        Lv10-14 加護: 射の技が広がる  掘り尽くされ捨てられた坑道。錆と獣の巣
//	 4 銀鏡の湖          Lv15-19 加護: 射光            月を映す湖。最後の射の加護がここに眠る
//	 5 朽ちた王城        Lv20-26 なし                  竜の気配に滅んだ王都。得るものはなく、試されるだけ
//	 6 煉獄の火山        Lv27-33 加護: 斬光・打炎      炎輝イグナが炉を残した山。武具が焼き直される
//	 7 氷晶の尖塔        Lv34-41 加護: 打水            水輝ミレイアが凍りついたまま眠る塔
//	 8 世界樹の樹海      Lv42-49 なし                  全 60 体。旅路で最も長く、最も迷う森
//	 9 深淵の迷宮        Lv50-58 加護: 射闇（最後）    闇輝ノクスの眠る底。ここで加護が出揃う
//	10 竜骨の墓所        Lv59-68 なし                  古の竜たちの骨が積もる谷
//	11 六輝の神殿        Lv69-79 なし                  六柱が封印を施した場所。もう誰もいない
//	12 裂けた空          Lv80-90 全 18 が揃う          封印の際。この先にはヴァリアスしかいない
//
// 三幕として読むとこうなる。
//
//	第一幕 旅立ち（Lv1-19  / 130 体）1〜4 と連続で加護が増える。旅がいちばん軽い
//	第二幕 試練　（Lv20-49 / 204 体）朽ちた王城で初めて足が止まり、樹海で最も深く迷う
//	第三幕 決戦　（Lv50-90 / 166 体）深淵の迷宮で加護が出揃い、あとは積み上げたもので進む
//
// ■ 陽だまりの草原だけは特別扱い（重要・仕様）
//
// 文化祭では QR コードを会場にばらばらに配置する。プレイヤーがどの魔物に
// 最初に出会うかを制御できない。したがって陽だまりの草原の 24 体は
//
//	「素手・Lv1・どの 1 体から始めても必ず勝てる」
//
// を満たさなければならない。ここが崩れると、最初の 1 体で詰んで
// 二度と遊べない参加者が出る。守るべき不変条件は次の 2 つ。
//
//	1. 耐性は 0 以下（等倍か弱点）のみ。軽減・無効・吸収を置かない
//	   → 素手（打 × 無）が必ず通る
//	2. 素手で削り切るターン数が、倒されるターン数より十分に短い
//
// validate() の firstAreaMustBeBeatableBareHanded がこれを機械的に守っている。
// バランス調整の都合で緩めてはいけない。
//
// ■ 名前の付け方
//
//	武器　　「◯◯の<種別>」。◯◯は属性 × 土地の格で決まり、進むほど格が上がる
//	　　　　（石 → 鉄 → 鋼 → 銀 → 白銀 → ミスリル → … → 神鋼）
//
//	回復薬　薬草から霊薬へ。終盤は六輝や世界樹に由来する名になる
//	加護薬　「◯の加護」（弱）「◯の祝福」（強）。自分の属性攻撃を高める
//	呪具　　「◯砕きの呪符」（弱）「◯断ちの呪印」（強）。相手の耐性を削る
//
//	魔物　　「<歪みの深さ><種族>」。竜の気配に当てられるほど呼び名が変わる
//
//		無 ストーン → アイアン → ミスリル    炎 フレイム → ブレイズ → インフェルノ
//		水 アクア   → フロスト → アビス      森 リーフ   → ソーン   → エルダー
//		光 シャイン → ルミナス → セラフィ    闇 シャドウ → カース   → ヴォイド
//
// 種族は土地に合わせて選ぶ。墓所にスライムは出さないし、草原にリッチは出さない。
// 同じ種族のより歪んだ個体は、後の土地で再登場する。
//
// ============================================================================
