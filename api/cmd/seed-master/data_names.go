// ============================================================================
// 原型の名前と由来 — 全 252 系統
//
// 命名の考え方は story.go の「名前の付け方」を参照。ここは 1 体ずつ手で
// 名付けたものの記録で、なぜその名前なのかを残しておく台帳にあたる。
//
// --- 最重要 : 由来の語をそのまま使わない -----------------------------------
//
// 「底無し」を ソコナシ、「暗がり」を クラガリ と書いただけでは、それは
// 日本語をカタカナに直しただけで名前になっていない。読んだ人は単語として
// 認識してしまい、その魔物の固有名として頭に残らない。
//
// ドラキーがドラキュラを崩したものであるように、由来の語は必ず一箇所以上
// 崩して、辞書に載っていない響きにする。
//
//	底無し  → ゾコナス   （濁点を移し、語尾を差し替え）
//	暗がり  → クラガレム （語尾を伸ばして別語に）
//	つくねん→ ツクネス   （語尾を差し替え）
//
// 崩し方は次のいずれか、または組み合わせ。
//
//	1. 濁点を付ける・外す・別の音へ移す      底 → ゾコ
//	2. 語尾を差し替える                      -ス -ム -ル -ゴ -ガ -ドン -レ -ネ
//	3. 母音を伸ばす・詰める                  ホタル → ホタール
//	4. 語中の音を入れ替える                  カガミ → カギマ
//	5. 二語を継ぎ目で潰して混ぜる            骨 + 絡み → ホネガラム
//
// 崩したあとに元の語が分かる程度には面影を残すこと。跡形もなくなると
// 由来を書く意味がなくなる。
//
// --- 名前の構造 -------------------------------------------------------------
//
// すべての名前は「前部 + 後部」の 2 つに分けられるように作ってある。
// これは武器とアイテムの名前が、その魔物の名前の一部を借りるため。
//
//	ゴシャハギ  前部 ゴシャ / 後部 ハギ
//	  → 武器      ゴシャアックス   （前部 + 武器種のカタカナ）
//	  → アイテム  ハギの鱗         （後部 + 部位）
//
// 借りるのが名前全体ではなく一部なのは、「ゴシャハギの斧」だと図鑑の索引の
// ようになって手触りが失われるから。一部だけ響きが残っていると、手に入れた
// 武器から倒した相手を思い出せる。
//
// --- 名付けるときの決まり ---------------------------------------------------
//
//	1. 前部・後部とも 2〜3 音。名前自体は 3〜6 音に収める
//	   前部は名前の先頭から、後部は末尾から切り出す。重なってよい
//	2. 前部は様態・質感（擬音、色、温度、動き）を担う
//	3. 後部は生き物らしさ（体の部位、獣の呼び名、古語）を担う
//	4. 由来は必ず書く。書けない名前は採用しない
//	5. 属性名や種族名をそのまま入れない（フレイム、ウルフ等は禁止）
//	6. 崩す前の語がそのまま名前になっていないか、必ず読み返して確かめる
//
// 亜種の名前は原型を崩して自動で作られる。ここで定義するのは原型だけ。
// ============================================================================

// speciesName は原型 1 体分の名前と由来。
type speciesName struct {
	Name  string // 表示名
	Front string // 前部。名前の先頭を切り出したもの。武器名に借りる
	Back  string // 後部。名前の末尾を切り出したもの。アイテム名に借りる
	// Front と Back は名前の一部を借りるためのものなので、重なってもよいし、
	// 合わせて名前全体を覆っていなくてもよい（モコル → モコ / コル）。
	// 借りたときに元の響きが残ることだけが条件。
	Origin string // 由来。崩す前の語と、その魔物の姿
}

