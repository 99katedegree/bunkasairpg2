// ============================================================================
// 魔物の名前と由来 — 全 500 体 / 161 系統
//
// 命名の考え方は story.go の「名前の付け方」を参照。
// このファイルが 500 体すべての名前の出どころで、生成器はここを読むだけ。
// 名前を変えたければここを直す。
//
// --- 造語の作り方 : 外国語の語根を 2 つ繋ぐ --------------------------------
//
// 日本語をそのまま使うと、どれだけ崩しても元の語が読めてしまう。
//
//	裂け目 → サケメル   ダメ。「裂け目」が読める
//	守護   → シュゴウル ダメ。「守護」が読める
//
// 由来はラテン語・ドイツ語（一部ギリシャ語）から取り、語根をカタカナに
// 写して 2 つ繋ぐ。日本語話者には意味が見えないので単語として処理されず、
// それでいて由来は実在する。ドラキーがドラキュラの崩しであるのと同じ。
//
//	nebula（羅・霧）+ dens（羅・牙） → ネブデンス
//	Moos（独・苔）  + Zahn（独・牙） → モスツァン
//
// --- 系統と崩れた個体 -------------------------------------------------------
//
// Species が同じ行は同じ系統。図鑑番号の上位 3 桁を共有する。
// 系統の先頭が原型で、以降は竜の気配を深く受けるほど名前が変形していく。
//
// 変形はラテン語で行う。由来が羅語の語根なので、崩し方も同じ言語体系に揃えた。
// 名前から「どの属性に転じたか」と「どれだけ深く歪んだか」の両方が読める。
//
//	モスピル          原型。Moos（独・苔）から。森の属性を持つ
//	モスピルイグニ    ignis（羅・火）。炎に転じた個体
//	スブモスピルンダ  sub- + unda（羅・波）。より深いところで水に転じた個体
//	ペルモスピルクス  per- + lux（羅・光）。徹底して歪み、光に転じた個体
//
//	接頭辞が歪みの深さ    なし → スブ → ペル → ウル → デ
//	語尾が転じた属性      フェル 無 / イグニ 炎 / ウンダ 水 /
//	                      シルワ 森 / ルクス 光 / ウンブラ 闇
//
// 転じる先の順番は系統ごとに違う。全系統が同じ順で回ると「炎の次は水」と
// 読めてしまい、崩れた個体に出会う驚きがなくなる。系統番号で開始位置を
// ずらしてあるので、どの属性に転じるかは戦うまで分からない。
//
// 原型の属性は名前の由来から決まる。Moos（苔）なら森、ros（露）なら水。
// 設定と数値が食い違わないよう、Element はこの台帳が持ち、生成器は
// ここを読むだけにしてある。
//
// --- 前部と後部 -------------------------------------------------------------
//
// Front は名前の先頭、Back は末尾を切り出したもの。武器とアイテムの名前が
// ここを借りる。重なってもよいし、合わせて名前全体を覆っていなくてもよい。
//
//	ネブデンス → 武器 ネブアックス / アイテム デンスの牙
//
// --- 数を変えるとき ---------------------------------------------------------
//
// 行数がそのまま魔物の数になる。土地ごとの行数は areaDefs の Count と
// 一致していなければならない。増やすときは両方を直すこと。
// ============================================================================

// monsterName は魔物 1 体分の名前と由来。
type monsterName struct {
	Species int    // 系統番号。同じ番号は同じ系統で、図鑑番号の上位 3 桁を共有する
	Name    string // 表示名
	Front   string // 前部。名前の先頭を切り出したもの。武器名に借りる
	Back    string // 後部。名前の末尾を切り出したもの。アイテム名に借りる
	Element string // この個体の属性。原型は由来から、崩れた個体は転じた先
	Origin  string // 由来。原型は語根、崩れた個体は転じた属性と歪みの深さ
}

