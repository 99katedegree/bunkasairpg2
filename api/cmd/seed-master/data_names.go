// 命名の考え方は story.go の「名前の付け方」を参照。
// このファイルが 500 体すべての名前の出どころで、生成器はここを読むだけ。
// 名前を変えたければここを直す。
//
// --- 造語の作り方 : 外国語の語根を 2 つ繋ぐ --------------------------------
//
// 日本語をそのまま使うと、どれだけ崩しても元の語が読めてしまう。
//
//	裂け目 → サケメル   ダメ。「裂け目」が読める
//	守護   → シュゴウル ダメ。「守護」が読める
//
// 由来はラテン語・ドイツ語（一部ギリシャ語）から取り、語根をカタカナに
// 写して 2 つ繋ぐ。日本語話者には意味が見えないので単語として処理されず、
// それでいて由来は実在する。ドラキーがドラキュラの崩しであるのと同じ。
//
//	nebula（羅・霧）+ dens（羅・牙） → ネブデンス
//	Moos（独・苔）  + Zahn（独・牙） → モスツァン
//
// --- 系統と崩れた個体 -------------------------------------------------------
//
// Species が同じ行は同じ系統。図鑑番号の上位 3 桁を共有する。
// 系統の先頭が原型で、以降は竜の気配を深く受けるほど名前が変形していく。
//
// 変形はラテン語の語形変化で行う。由来が羅語の語根なので、崩し方も同じ
// 言語体系に揃えた。どの形にも意味があり、崩れの深さが名前から読める。
//
//	ネブデンス        原型
//	ネブデンシオル    -ior  比較級。より深く歪んだもの
//	スブネブデンス    sub-  より下の。さらに深いところに現れる個体
//	ペルネブデンシオル per- 徹底して。深く歪み、なお進んだもの
//	ネブデンシム      -imus 最上級。その系統で最も深く歪んだもの
//
// 語形は実在するもの（clarus 明るい → clarior より明るい → clarissimus）。
// 末尾の音に合わせて綴りを変える（-ス → -シオル、-ム → -モル）ので、
// 同じ音が重なって言いにくくなることがない。
//
// --- 前部と後部 -------------------------------------------------------------
//
// Front は名前の先頭、Back は末尾を切り出したもの。武器とアイテムの名前が
// ここを借りる。重なってもよいし、合わせて名前全体を覆っていなくてもよい。
//
//	ネブデンス → 武器 ネブアックス / アイテム デンスの牙
//
// --- 数を変えるとき ---------------------------------------------------------
//
// 行数がそのまま魔物の数になる。土地ごとの行数は areaDefs の Count と
// 一致していなければならない。増やすときは両方を直すこと。
// ============================================================================

